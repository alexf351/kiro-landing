#!/usr/bin/env node
// Keep sitemap.xml, sitemap-index.xml and llms.txt complete, from the pages
// that are actually published.
//
//   node scripts/seo-indexes.mjs           rewrite the three files
//   node scripts/seo-indexes.mjs --check   report what would change, write nothing
//   node scripts/seo-indexes.mjs --deploy  what Vercel runs before every deploy:
//                                          rewrite, and never fail the deploy
//
// Why this exists: sitemap.xml and llms.txt were hand-maintained, so new blog
// posts never reached them (llms.txt listed 88 of 142 posts; sitemap.xml listed
// none and relied on blog-sitemap.xml alone). This script scans the served HTML
// (root pages, blog/*.html and any <locale>/blog/*.html) on every Vercel build,
// so a post that is merged is in the sitemap and llms.txt of that same deploy,
// with no edit to either file. It reads only served files, because
// .vercelignore removes blog-engine/ (and its JSON content) before the build.
//
// What it writes:
//   sitemap.xml       the AUTO block: every indexable page not already listed by
//                     hand or in the PATHS block, with lastmod from the page's own
//                     dateModified and hreflang alternates taken from the page.
//                     Entries outside the block are left exactly as they are.
//   sitemap-index.xml lastmod of sitemap.xml and blog-sitemap.xml.
//   llms.txt          the "## Every blog post, by topic" section. The rest of
//                     the file stays hand-written.
//
// A page is indexable when it has <link rel="canonical"> pointing at its own
// URL on https://tryiro.com and no robots noindex. The committed copies of the
// three files are refreshed whenever someone runs this script; the live site
// is regenerated on every deploy either way.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const D = 'https://tryiro.com';
const CHECK = process.argv.includes('--check');
const DEPLOY = process.argv.includes('--deploy');
// On Vercel a failure here must not block the deploy: the committed copies of
// the three files are served unchanged instead.
if (DEPLOY) {
  process.on('uncaughtException', (e) => {
    console.warn(`seo-indexes: skipped, serving the committed files (${e && e.message})`);
    process.exit(0);
  });
}

const AUTO_START = '<!-- AUTO:START (generated by scripts/seo-indexes.mjs: do not edit by hand) -->';
const AUTO_END = '<!-- AUTO:END -->';
const LLMS_HEADING = '## Every blog post, by topic';
const LLMS_BEFORE = '## Topic pages'; // where the section goes the first time

const SKIP_DIRS = new Set(['.git', '.github', '.claude', '.vercel', 'node_modules', 'assets', 'blog-engine', 'llms',
  'scripts', 'data', 'aso', 'growth', 'research']);
const LANG_NAMES = { en: 'English', de: 'Deutsch', es: 'Español', fr: 'Français', it: 'Italiano', 'pt-br': 'Português',
  pt: 'Português', 'zh-hans': '中文', zh: '中文', ja: '日本語', ko: '한국어' };

// ---------- read the published pages ----------
function htmlFiles(dir = ROOT, rel = '') {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) {
      if (SKIP_DIRS.has(e.name) || e.name.startsWith('design_handoff') || e.name.startsWith('.')) continue;
      out.push(...htmlFiles(path.join(dir, e.name), rel + e.name + '/'));
    } else if (e.name.endsWith('.html')) out.push(rel + e.name);
  }
  return out;
}
const urlFor = (file) => {
  let p = file.replace(/\.html$/, '').replace(/(^|\/)index$/, '');
  return p ? `${D}/${p}` : `${D}/`;
};
const norm = (u) => (u.replace(/\/+$/, '') || u).replace(/^https:\/\/www\./, 'https://');
const decode = (s) =>
  s.replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;|&#x27;|&apos;/g, "'").replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>').replace(/&nbsp;/g, ' ').replace(/&mdash;/g, '—').replace(/&ndash;/g, '–')
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n));
const xml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const attr = (tag, name) => {
  const m = tag.match(new RegExp(`\\s${name}\\s*=\\s*"([^"]*)"`, 'i')) || tag.match(new RegExp(`\\s${name}\\s*=\\s*'([^']*)'`, 'i'));
  return m ? m[1] : '';
};

function readPage(file) {
  const html = fs.readFileSync(path.join(ROOT, file), 'utf8');
  const head = (html.match(/<head[\s>][\s\S]*?<\/head>/i) || [html])[0];
  const links = head.match(/<link\b[^>]*>/gi) || [];
  const metas = head.match(/<meta\b[^>]*>/gi) || [];
  const meta = (key) => {
    const t = metas.find((m) => attr(m, 'name').toLowerCase() === key || attr(m, 'property').toLowerCase() === key);
    return t ? decode(attr(t, 'content')) : '';
  };
  const canonicalTag = links.find((l) => /\brel\s*=\s*["']canonical["']/i.test(l));
  const alternates = links
    .filter((l) => /\brel\s*=\s*["']alternate["']/i.test(l) && attr(l, 'hreflang'))
    .map((l) => ({ lang: attr(l, 'hreflang'), href: attr(l, 'href') }));
  const dates = (key) => [...html.matchAll(new RegExp(`"${key}"\\s*:\\s*"(\\d{4}-\\d{2}-\\d{2})`, 'g'))].map((m) => m[1]);
  const modified = [...dates('dateModified'), meta('article:modified_time').slice(0, 10)].filter(Boolean).sort().pop() || '';
  const published = [...dates('datePublished'), meta('article:published_time').slice(0, 10)].filter(Boolean).sort()[0] || '';
  // Breadcrumb trail: Iro AI > Blog > Hub > Post.
  let crumbs = [];
  const bc = html.match(/"BreadcrumbList"[\s\S]*?"itemListElement"\s*:\s*(\[[\s\S]*?\])\s*\}/);
  if (bc) {
    try { crumbs = JSON.parse(bc[1]).map((c) => ({ name: c.name, url: norm(c.item?.['@id'] || c.item || '') })); } catch {}
  }
  const h1 = html.match(/<h1\b[^>]*>([\s\S]*?)<\/h1>/i);
  const title = decode((h1 ? h1[1] : (head.match(/<title>([\s\S]*?)<\/title>/i) || [, ''])[1]).replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ').trim();
  return {
    file,
    url: urlFor(file),
    canonical: canonicalTag ? norm(attr(canonicalTag, 'href')) : '',
    noindex: /noindex/i.test(meta('robots')),
    alternates,
    modified: modified || published,
    published,
    crumbs,
    title,
    description: meta('description').replace(/\s+/g, ' ').trim(),
    lang: (html.match(/<html\b[^>]*\blang\s*=\s*"([^"]+)"/i) || [, 'en'])[1],
  };
}

const pages = htmlFiles().map(readPage);
const byUrl = new Map(pages.map((p) => [norm(p.url), p]));
const indexable = pages.filter((p) => !p.noindex && p.canonical && p.canonical === norm(p.url));

// hreflang alternates, kept only when the page lists itself and each target is a
// published, indexable page (a link to a translation that does not exist yet
// would make the whole cluster invalid).
function cleanAlternates(p) {
  const ok = p.alternates.filter((a) => {
    const t = byUrl.get(norm(a.href));
    return t && !t.noindex && t.canonical === norm(t.url);
  });
  const langs = ok.filter((a) => a.lang.toLowerCase() !== 'x-default');
  if (langs.length < 2 || !ok.some((a) => norm(a.href) === norm(p.url))) return [];
  return ok;
}

// ---------- sitemap.xml ----------
const smFile = path.join(ROOT, 'sitemap.xml');
const smOld = fs.readFileSync(smFile, 'utf8');
let smBase = smOld;
{
  const a = smBase.indexOf(AUTO_START);
  const b = smBase.indexOf(AUTO_END);
  if (a !== -1 && b > a) smBase = smBase.slice(0, a).replace(/[ \t]*$/, '') + smBase.slice(b + AUTO_END.length).replace(/^\n/, '');
}
const listed = new Set([...smBase.matchAll(/<url>\s*<loc>([^<]+)<\/loc>/g)].map((m) => norm(m[1].trim())));
const warnings = [];
for (const u of listed) {
  const p = byUrl.get(u);
  if (!p) warnings.push(`sitemap.xml lists ${u} but no published file serves it`);
  else if (p.noindex) warnings.push(`sitemap.xml lists ${u} but the page is noindex`);
  else if (p.canonical && p.canonical !== u) warnings.push(`sitemap.xml lists ${u} but its canonical is ${p.canonical}`);
}
const rank = (u) => (u === `${D}/blog` ? '0' : /^https:\/\/tryiro\.com\/blog\//.test(u) ? '1' : /\/blog\//.test(u) ? '2' : '3') + u;
const auto = indexable.filter((p) => !listed.has(norm(p.url))).sort((x, y) => (rank(x.url) < rank(y.url) ? -1 : 1));
const entry = (p) => {
  const lines = [`  <url>`, `    <loc>${xml(p.url)}</loc>`];
  if (p.modified) lines.push(`    <lastmod>${p.modified}</lastmod>`);
  for (const a of cleanAlternates(p)) lines.push(`    <xhtml:link rel="alternate" hreflang="${xml(a.lang)}" href="${xml(norm(a.href) === `${D}` ? `${D}/` : a.href)}"/>`);
  lines.push(`  </url>`);
  return lines.join('\n');
};
const block = [`  ${AUTO_START}`, ...auto.map(entry), `  ${AUTO_END}`].join('\n');
let smNew = smBase.replace(/\n?<\/urlset>\s*$/, `\n${block}\n</urlset>\n`);
if (!/xmlns:xhtml=/.test(smNew)) smNew = smNew.replace('<urlset ', '<urlset xmlns:xhtml="http://www.w3.org/1999/xhtml" ');

// ---------- sitemap-index.xml ----------
const idxFile = path.join(ROOT, 'sitemap-index.xml');
const idxOld = fs.existsSync(idxFile) ? fs.readFileSync(idxFile, 'utf8') : '';
const newest = (src) => [...src.matchAll(/<lastmod>(\d{4}-\d{2}-\d{2})/g)].map((m) => m[1]).sort().pop();
const idxNew = idxOld.replace(/(<loc>https:\/\/tryiro\.com\/([^<]+)<\/loc>\s*<lastmod>)([^<]+)(<\/lastmod>)/g, (all, p1, name, old, p4) => {
  if (name !== 'sitemap.xml' && name !== 'blog-sitemap.xml') return all;
  const f = path.join(ROOT, name);
  const d = newest(name === 'sitemap.xml' ? smNew : fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '');
  return p1 + (d && d > old ? d : old) + p4;
});

// ---------- llms.txt ----------
const llmsFile = path.join(ROOT, 'llms.txt');
const llmsOld = fs.readFileSync(llmsFile, 'utf8');
const isBlog = (p) => /^blog\/[^/]+\.html$/.test(p.file) && p.file !== 'blog/index.html';
const blogPages = indexable.filter(isBlog);
const isHub = (p) => p.crumbs.length === 3 && p.crumbs[2].url === norm(p.url);
const hubs = blogPages.filter(isHub);
// Hubs in the order the blog index presents them.
const indexHtml = byUrl.get(`${D}/blog`) ? fs.readFileSync(path.join(ROOT, 'blog/index.html'), 'utf8') : '';
const hubPos = (h) => {
  const i = indexHtml.indexOf(`/blog/${path.basename(h.file, '.html')}"`);
  return i === -1 ? Infinity : i;
};
hubs.sort((a, b) => hubPos(a) - hubPos(b) || a.url.localeCompare(b.url));
const hubName = (h) => {
  const n = (h.crumbs[2]?.name || h.title).split(':')[0].trim();
  return n.replace(/\s*\((?:\d{4})\)$/, '');
};
const posts = blogPages.filter((p) => !isHub(p));
const hubOf = (p) => (p.crumbs.length >= 4 ? hubs.find((h) => norm(h.url) === p.crumbs[2].url) : undefined);
const newestFirst = (a, b) => (b.published || '').localeCompare(a.published || '') || a.url.localeCompare(b.url);
const translations = (p) =>
  cleanAlternates(p)
    .filter((a) => a.lang.toLowerCase() !== 'x-default' && norm(a.href) !== norm(p.url))
    .map((a) => `[${LANG_NAMES[a.lang.toLowerCase()] || a.lang}](${a.href})`);
const clip = (s, n = 200) => (s.length <= n ? s : s.slice(0, s.lastIndexOf(' ', n - 1)).replace(/[\s,;:.—-]+$/, '') + '…');
const line = (p) => {
  const also = translations(p);
  const desc = p.description ? `: ${clip(p.description)}` : '';
  return `- [${p.title}](${p.url})${desc}${also.length ? ` Also in ${also.join(', ')}.` : ''}`;
};
const groups = hubs.map((h) => ({ head: `### [${hubName(h)}](${h.url})`, items: posts.filter((p) => hubOf(p) === h) }));
const loose = posts.filter((p) => !hubOf(p));
if (loose.length) groups.push({ head: '### Other posts', items: loose });
const section = [
  LLMS_HEADING,
  '',
  `${posts.length} posts in ${hubs.length} topic hubs, newest first within each hub. Generated from the published pages on every deploy (scripts/seo-indexes.mjs).`,
  ...groups.filter((g) => g.items.length).flatMap((g) => ['', g.head, ...g.items.sort(newestFirst).map(line)]),
  '',
  '',
].join('\n');
let llmsNew;
{
  const s = llmsOld.indexOf(`\n${LLMS_HEADING}\n`);
  if (s !== -1) {
    const after = llmsOld.indexOf('\n## ', s + LLMS_HEADING.length + 2);
    llmsNew = llmsOld.slice(0, s + 1) + section + (after === -1 ? '' : llmsOld.slice(after + 1));
  } else {
    const at = llmsOld.indexOf(`\n${LLMS_BEFORE}`);
    llmsNew = at === -1 ? llmsOld.replace(/\s*$/, '\n\n') + section : llmsOld.slice(0, at + 1) + section + llmsOld.slice(at + 1);
  }
}

// ---------- write / report ----------
const count = (s) => (s.match(/<url>/g) || []).length;
const changes = [
  ['sitemap.xml', smOld, smNew],
  ['sitemap-index.xml', idxOld, idxNew],
  ['llms.txt', llmsOld, llmsNew],
].filter(([, a, b]) => a !== b);
for (const w of warnings) console.warn(`  warning: ${w}`);
console.log(`seo-indexes: ${indexable.length} indexable pages; sitemap.xml ${count(smOld)} -> ${count(smNew)} URLs ` +
  `(${auto.length} generated); llms.txt lists ${posts.length} posts in ${hubs.length} hubs`);
if (CHECK) {
  console.log(changes.length ? `  would change: ${changes.map((c) => c[0]).join(', ')}` : '  nothing to change');
  process.exit(changes.length ? 1 : 0);
}
for (const [name, , next] of changes) fs.writeFileSync(path.join(ROOT, name), next);
console.log(changes.length ? `  wrote ${changes.map((c) => c[0]).join(', ')}` : '  nothing to change');
